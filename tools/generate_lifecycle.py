"""Generate the versioned lifecycle interface from the authoritative lab source."""
from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PARAMS = """param(
    [Parameter(Mandatory)][ValidatePattern('^[a-z][a-z0-9-]{2,23}$')][string]$RunId,
    [string]$GithubOwner = $env:AZ400_GITHUB_OWNER,
    [string]$AdoOrganization = $env:AZ400_ADO_ORGANIZATION,
    [string]$SubscriptionId = $env:AZ400_SUBSCRIPTION_ID,
    [string]$Location = 'westeurope',
    [switch]$Execute, [switch]$ProvisionOnly, [switch]$AcknowledgeCost,
    [switch]$AcknowledgeTenantChange, [switch]$AllowPaidFeatures
)
"""


def outputs():
    labs = json.loads((ROOT / "curriculum/lab-content.yml").read_text(encoding="utf-8"))["labs"]
    files = {}
    for lab in labs:
        folder = ROOT / "labs" / lab["slug"]
        files[folder / "lab.yml"] = json.dumps({"schemaVersion": "1.0.0", **lab}, indent=2, ensure_ascii=False) + "\n"
        for operation in ("Preflight", "Setup", "Validate", "Cleanup"):
            files[folder / "scripts/cli" / (operation + ".ps1")] = (
                "#Requires -Version 7.4\n# Generated by tools/generate_lifecycle.py; edit the source, then regenerate.\n"
                "[CmdletBinding()]\n" + PARAMS +
                "$ErrorActionPreference = 'Stop'\n"
                "$root = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '../../../..'))\n"
                "Import-Module (Join-Path $root 'tools/Az400.Lifecycle.psm1') -Force\n"
                "$definition = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '../../lab.yml'))\n"
                f"Invoke-Az400Lab -Operation {operation} -Definition $definition @PSBoundParameters\n"
            )
        files[folder / "scripts/cli/Context.ps1"] = (
            "#Requires -Version 7.4\n# Dot-source this generated script after provisioning an owned run.\n"
            "[CmdletBinding()]\n" + PARAMS.replace(
                ",\n    [switch]$Execute, [switch]$ProvisionOnly, [switch]$AcknowledgeCost,\n    [switch]$AcknowledgeTenantChange, [switch]$AllowPaidFeatures", ""
            ) +
            "$ErrorActionPreference = 'Stop'\n"
            "$root = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '../../../..'))\n"
            "Import-Module (Join-Path $root 'tools/Az400.Lifecycle.psm1') -Force\n"
            "$definition = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '../../lab.yml'))\n"
            "$context = Get-Az400Context -Definition $definition @PSBoundParameters\n"
            "if (-not (Test-Path -LiteralPath (Join-Path $context.workRoot 'run.json'))) { throw 'Provision the owned run first with Setup.ps1 -ProvisionOnly -Execute.' }\n"
            "$RepoRoot = $context.repoRoot; $LabRoot = $context.labRoot; $WorkRoot = $context.workRoot\n"
            "$GhRepo = $context.ghRepo; $AdoProject = $context.adoProject; $ResourceGroup = $context.resourceGroup\n"
            "Write-Verbose ('Owned run context: {0}; {1}; {2}; {3}; {4}; {5}' -f $RepoRoot,$LabRoot,$WorkRoot,$GhRepo,$AdoProject,$ResourceGroup)\n"
        )
        fixture = {"schemaVersion": "1.0.0", "labId": lab["id"], "runId": "fixture-demo", "status": "passed",
                   "checkpoints": [{"id": f"CP{i}", "status": "passed"} for i in range(1, 6)], "verifiedAt": "2026-10-16T00:00:00Z"}
        files[folder / "tests/fixtures/validation.sample.json"] = json.dumps(fixture, indent=2) + "\n"
        files[folder / "tests/fixtures/cleanup.sample.json"] = json.dumps(
            {"schemaVersion": "1.0.0", "labId": lab["id"], "runId": "fixture-demo", "status": "passed", "residual": [], "retained": []}, indent=2) + "\n"
        files[folder / "tests/fixtures/run.sample.json"] = json.dumps({
            "schemaVersion": "1.0.0", "labId": lab["id"], "runId": "fixture-demo",
            "ownerToken": "0" * 32,
            "context": {"labId": lab["id"], "runId": "fixture-demo", "githubOwner": "", "adoOrganization": "", "subscriptionId": "", "location": "westeurope"},
            "status": "initialized", "objects": [], "checkpoints": [], "liveVerified": False
        }, indent=2) + "\n"
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    generated = outputs()
    for path, expected in generated.items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != expected:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected, encoding="utf-8", newline="\n")
    if stale:
        raise SystemExit("Stale lifecycle files:\n" + "\n".join(stale))
    print(f"Lifecycle {'verified' if args.check else 'generated'}: {len(generated)} files across 28 labs")


if __name__ == "__main__":
    main()
