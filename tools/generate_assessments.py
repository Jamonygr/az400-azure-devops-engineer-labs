#!/usr/bin/env python3
"""Render assessment views from authoritative questions.yml. No question authoring."""
from __future__ import annotations
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

def read_data(path):
    text = Path(path).read_text(encoding="utf-8")
    try:
        return json.loads(text)
    except json.JSONDecodeError:
        import yaml
        return yaml.safe_load(text)

def render_lab(data, answers=False):
    title = f"Lab {data['labId']} — {'Answers and explanations' if answers else 'Scenario questions'}"
    out = [f"# {title}", "", "<!-- Generated from questions.yml; edit that file and run tools/generate_assessments.py. -->", "", f"Verified: {data['verifiedDate']}. Original practice material; no recalled exam questions.", ""]
    if not answers:
        out += ["Choose the single best answer for every question. Use [the answer guide](ANSWERS.md) after attempting the questions.", ""]
    for q in data["questions"]:
        checkpoint = f"[{q['checkpointId']}](README.md#task-{q['checkpointId'][2:]})"
        objective_links = ", ".join(f"[{oid}](../../docs/objective-map.md)" for oid in q['objectiveIds'])
        out += [f"## {q['id']}", "", f"{q['difficulty'].title()} · {checkpoint} · {objective_links}", "", q['question'], ""]
        for option in q["options"]:
            if answers:
                mark = " **Correct.**" if option["key"] in q["correctAnswers"] else ""
                out += [f"- **{option['key']}. {option['text']}**{mark} {option['rationale']}"]
            else:
                out += [f"- **{option['key']}.** {option['text']}"]
        out.append("")
        if answers:
            source_map = {s["id"]: s["url"] for s in data["sources"]}
            out += [f"**Explanation:** {q['explanation']}", "", "**Sources:** " + "; ".join(f"[{s}]({source_map[s]})" for s in q["sourceIds"]), ""]
    return "\n".join(out).rstrip() + "\n"

def generated_files(root=ROOT):
    rows = []
    for path in sorted((root / "labs").glob("*/questions.yml")):
        data = read_data(path)
        rows.append((path, data))
        yield path.with_name("QUESTIONS.md"), render_lab(data)
        yield path.with_name("ANSWERS.md"), render_lab(data, True)
    out = ["# Question bank index", "", "<!-- Generated by tools/generate_assessments.py. -->", "", "1,250 original scenario questions across the 25 assessed labs. Each lab contains 15 foundational, 25 applied, and 10 advanced questions. Checkpoint references follow the most relevant practical task; counts vary by checkpoint.", "", "| Lab | Questions | Answers | Foundational | Applied | Advanced |", "|---|---|---|---:|---:|---:|"]
    for path, data in rows:
        relative = f"../labs/{path.parent.name}"
        out.append(f"| {data['labId']} | [50 questions]({relative}/QUESTIONS.md) | [Explanations]({relative}/ANSWERS.md) | 15 | 25 | 10 |")
    out += ["", "Lab 00 establishes prerequisites. Labs 26 and 27 are integrated capstones and have evidence-based rubrics rather than additional question counts.", "", "See [assessment guidance](assessment-guide.md) for scoring, question provenance, and maintenance.", ""]
    yield root / "docs" / "question-bank-index.md", "\n".join(out)

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if generated Markdown differs; do not write.")
    args = parser.parse_args()
    stale = []
    count = 0
    for path, content in generated_files():
        count += 1
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
    if stale:
        raise SystemExit("Assessment views are stale:\n" + "\n".join(stale))
    print(f"{'Checked' if args.check else 'Generated'} {count} assessment Markdown views.")

if __name__ == "__main__":
    main()
